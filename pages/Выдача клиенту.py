# ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
# ============================================================

engine = Config.get_engine()


# ============================================================
# ФУНКЦИЯ ЗАГРУЗКИ ДАННЫХ
# ============================================================

@st.cache_data
def load_data(query_name, params=None):

    try:

        query = AUTO_REFRESH_CLIENTS.get(query_name)

        if query is None:
            return pd.DataFrame()

        if params:

            df = pd.read_sql(
                query,
                engine,
                params=params
            )

        else:

            df = pd.read_sql(
                query,
                engine
            )

        return df

    except Exception as e:

        st.error(
            f"Ошибка загрузки отчета '{query_name}': {str(e)}"
        )

        return pd.DataFrame()


# ============================================================
# ОТОБРАЖЕНИЕ ОТЧЕТОВ
# ============================================================

def show_reports():

    if not AUTO_REFRESH_CLIENTS:

        st.info(
            "Нет настроенных отчетов для автообновления"
        )

        return

    # --------------------------------------------------------
    # Создаем колонки
    # --------------------------------------------------------

    cols = st.columns(
        len(AUTO_REFRESH_CLIENTS)
    )

    # --------------------------------------------------------
    # Перебираем отчеты
    # --------------------------------------------------------

    for idx, (report_name, query) in enumerate(
        AUTO_REFRESH_CLIENTS.items()
    ):

        col_idx = idx % len(cols)

        with cols[col_idx]:

            # st.subheader(report_name)

            # ------------------------------------------------
            # Загружаем данные
            # ------------------------------------------------

            df = load_data(report_name)

            # ------------------------------------------------
            # Если данных нет
            # ------------------------------------------------

            if df.empty:

                st.warning("Нет заказов для выдачи")

                continue

            # ------------------------------------------------
            # Таблица
            # ------------------------------------------------

            st.dataframe(
                df,
                use_container_width=True
            )

            # ------------------------------------------------
            # Определяем числовые колонки
            # ------------------------------------------------

            numeric_cols = df.select_dtypes(
                include=["number"]
            ).columns


# ============================================================
# SIDEBAR
# ============================================================

with st.sidebar:

    # --------------------------------------------------------
    # РУЧНОЕ ОБНОВЛЕНИЕ
    # --------------------------------------------------------

    if st.button(
        "🔄 Обновить данные",
        use_container_width=True
    ):

        now = datetime.now()

        # ----------------------------------------------------
        # Обновляем время последнего обновления
        # ----------------------------------------------------

        st.session_state.last_refresh_time = now

        # ----------------------------------------------------
        # Перезапускаем таймер с 20 секунд
        # ----------------------------------------------------

        st.session_state.next_refresh_time = (
            now.timestamp() + REFRESH_INTERVAL
        )

        # ----------------------------------------------------
        # Очищаем кэш
        # ----------------------------------------------------

        load_data.clear()

        st.rerun()
        
    st.header("⚙️ Настройки")

    # --------------------------------------------------------
    # АВТООБНОВЛЕНИЕ
    # --------------------------------------------------------

    st.subheader("🔄 Автообновление")

    auto_refresh = st.checkbox(
        "Включить автообновление (20 сек.)",
        value=st.session_state.auto_refresh_enabled
    )

    # --------------------------------------------------------
    # ИЗМЕНЕНИЕ СОСТОЯНИЯ АВТООБНОВЛЕНИЯ
    # --------------------------------------------------------

    if auto_refresh != st.session_state.auto_refresh_enabled:

        st.session_state.auto_refresh_enabled = auto_refresh

        # ----------------------------------------------------
        # Если включили автообновление
        # ----------------------------------------------------

        if auto_refresh:

            now = datetime.now()

            st.session_state.last_refresh_time = now

            st.session_state.next_refresh_time = (
                now.timestamp() + REFRESH_INTERVAL
            )

        # ----------------------------------------------------
        # Если выключили автообновление
        # ----------------------------------------------------

        else:

            st.session_state.next_refresh_time = (
                datetime.now().timestamp()
            )

        # ----------------------------------------------------
        # Очищаем кэш
        # ----------------------------------------------------

        load_data.clear()

        st.rerun()


# ============================================================
# ЗАГОЛОВОК
# ============================================================

# ============================================================
# FRAGMENT ДЛЯ АВТООБНОВЛЕНИЯ
# ============================================================

if st.session_state.auto_refresh_enabled:

    # --------------------------------------------------------
    # FRAGMENT
    #
    # Запускается каждые 1 секунду.
    #
    # Это нужно для красивого обратного отсчета.
    # Сами данные из БД обновляются только каждые 20 секунд.
    # --------------------------------------------------------

    @st.fragment(run_every=1)
    def auto_refresh_reports():

        now = datetime.now()

        # ----------------------------------------------------
        # Сколько секунд осталось
        # ----------------------------------------------------

        seconds_left = int(
            st.session_state.next_refresh_time
            - now.timestamp()
        )

        # ----------------------------------------------------
        # Если время обновления наступило
        # ----------------------------------------------------

        if seconds_left <= 0:

            # -----------------------------------------------
            # Очищаем кэш
            # -----------------------------------------------

            load_data.clear()

            # -----------------------------------------------
            # Фиксируем реальное время обновления
            # -----------------------------------------------

            refresh_time = datetime.now()

            st.session_state.last_refresh_time = refresh_time

            # -----------------------------------------------
            # Назначаем следующее обновление
            # -----------------------------------------------

            st.session_state.next_refresh_time = (
                refresh_time.timestamp()
                + REFRESH_INTERVAL
            )

            # -----------------------------------------------
            # Показываем 20 секунд до следующего обновления
            # -----------------------------------------------

            seconds_left = REFRESH_INTERVAL

        # ----------------------------------------------------
        # Защита от отрицательного значения
        # ----------------------------------------------------

        seconds_left = max(
            0,
            seconds_left
        )

        # ----------------------------------------------------
        # ИНФОРМАЦИЯ О ПОСЛЕДНЕМ ОБНОВЛЕНИИ
        # ----------------------------------------------------

        st.caption(
            "Последнее обновление: "
            f"{st.session_state.last_refresh_time.strftime('%Y-%m-%d %H:%M:%S')}"
        )

        # ----------------------------------------------------
        # ОБРАТНЫЙ ОТСЧЕТ
        # ----------------------------------------------------

        with st.sidebar:
            
            st.divider()
            st.markdown(
                f"""
                <div class="refresh-timer">
                    🔄 Следующее обновление через:
                    <span class="refresh-countdown">
                        {seconds_left} сек.
                    </span>
                </div>
                """,
                unsafe_allow_html=True
            )

        # ----------------------------------------------------
        # ОТЧЕТЫ
        # ----------------------------------------------------

        show_reports()


    # --------------------------------------------------------
    # ЗАПУСК FRAGMENT
    # --------------------------------------------------------

    auto_refresh_reports()


# ============================================================
# АВТООБНОВЛЕНИЕ 
# ============================================================

else:

    st.caption(
        "Последнее обновление: "
        f"{st.session_state.last_refresh_time.strftime('%Y-%m-%d %H:%M:%S')}"
    )

    st.info(
        "⏸️ Автообновление выключено"
    )

    show_reports()