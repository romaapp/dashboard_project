import streamlit as st
import uuid

from logger import logger
from auth import require_auth, logout_button


# ============================================================
# НАСТРОЙКА СТРАНИЦЫ
# ============================================================

st.set_page_config(
    page_title="Главная страница",
    page_icon="🏠",
    layout="wide",
    initial_sidebar_state="expanded"
)


# ============================================================
# НАСТРОЙКА НАВИГАЦИИ
# ============================================================

pages = [
    st.Page(
        "pages/Главная страница.py",
        title="🏠 Главная страница",
    ),

    st.Page(
        "pages/Дашборд отгрузки.py",
        title="📊 Дашборд отгрузки"
    ),

    st.Page(
        "pages/Выдача клиенту.py",
        title="📦 Выдача клиенту"
    ),

    st.Page(
        "pages/Разработка.py",
        title="🛠️ Разработка"
    ),

    st.Page(
        "pages/Честный знак.py",
        title="🏷️ Честный знак"
    ),

    st.Page(
        "pages/timeline.py",
        title="🕐 Timeline заявки"
    ),

    st.Page(
        "pages/admin.py",
        title="🔐 Администрирование"
    ),
]


# ============================================================
# ОТКРЫТЫЕ БЕЗ АВТОРИЗАЦИИ СТРАНИЦЫ
# ============================================================

PUBLIC_PAGES = [
    "📊 Дашборд отгрузки",
    "📦 Выдача клиенту",
]


# ============================================================
# ЗАПУСК НАВИГАЦИИ
# ============================================================

pg = st.navigation(pages)


# ============================================================
# ИНИЦИАЛИЗАЦИЯ СЕССИИ
# ============================================================

if "session_id" not in st.session_state:

    st.session_state.session_id = str(
        uuid.uuid4()
    )


# ============================================================
# ОПРЕДЕЛЯЕМ ТЕКУЩУЮ СТРАНИЦУ
# ============================================================

current_page = pg.title


# ============================================================
# ПРОВЕРКА ДОСТУПА
# ============================================================

# ------------------------------------------------------------
# ОТКРЫТЫЕ СТРАНИЦЫ
# ------------------------------------------------------------

if current_page in PUBLIC_PAGES:

    # --------------------------------------------------------
    # Запуск страницы без авторизации
    # --------------------------------------------------------

    pg.run()


# ------------------------------------------------------------
# ЗАЩИЩЕННЫЕ СТРАНИЦЫ
# ------------------------------------------------------------

else:

    if require_auth():

        # ====================================================
        # КНОПКА ВЫХОДА
        # ====================================================

        logout_button()

        # ====================================================
        # ЛОГИРОВАНИЕ ПОСЕЩЕНИЯ СТРАНИЦЫ
        # ====================================================

        if (
            st.session_state.get("last_logged_page")
            != current_page
        ):

            logger.log_action(
                "page_visit",
                current_page
            )

            st.session_state.last_logged_page = (
                current_page
            )

        # ====================================================
        # ЗАПУСК СТРАНИЦЫ
        # ====================================================

        pg.run()